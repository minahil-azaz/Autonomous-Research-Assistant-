"""
api/export.py — Markdown → PDF export endpoint.

POST /api/export
Body: {"markdown": "...", "topic": "..."}

Returns a styled, downloadable PDF using WeasyPrint.
Falls back to ReportLab if WeasyPrint is unavailable.
"""

import io
import re
import tempfile
from datetime import datetime

from fastapi import APIRouter
from fastapi.responses import Response
from pydantic import BaseModel

router = APIRouter()


class ExportRequest(BaseModel):
    markdown: str
    topic: str = "Research Report"


@router.post("/export")
async def export_pdf(req: ExportRequest):
    """Convert a Markdown report to a styled PDF and return it as a download."""
    html = _markdown_to_html(req.markdown, req.topic)
    pdf_bytes = _html_to_pdf(html)

    safe_name = re.sub(r"[^a-zA-Z0-9_-]", "-", req.topic)[:50]
    filename = f"research-{safe_name}.pdf"

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


