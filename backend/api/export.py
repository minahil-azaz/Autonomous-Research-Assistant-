def _markdown_to_html(md: str, topic: str) -> str:
    """Convert Markdown to full HTML document with styling."""
    body = _parse_md(md)
    date_str = datetime.now().strftime("%B %d, %Y")

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <style>{CSS}</style>
</head>
<body>
  <div class="report-header">
    <div class="report-meta">Autonomous Research Assistant &nbsp;·&nbsp; {date_str}</div>
  </div>
  {body}
  <div class="footer">
    Generated by Autonomous Research Assistant &nbsp;·&nbsp; {date_str}
  </div>
</body>
</html>"""


def _parse_md(md: str) -> str:
    """Minimal Markdown → HTML converter (covers the report's subset)."""
    lines = md.split("\n")
    html_parts = []
    i = 0

    while i < len(lines):
        line = lines[i]

        if line.startswith("### "):
            html_parts.append(f"<h3>{_inline(line[4:])}</h3>")
        elif line.startswith("## "):
            html_parts.append(f"<h2>{_inline(line[3:])}</h2>")
        elif line.startswith("# "):
            html_parts.append(f"<h1 style='font-size:20pt;font-weight:600;margin-bottom:8px'>{_inline(line[2:])}</h1>")
        elif line.startswith("> "):
            html_parts.append(f"<blockquote>{_inline(line[2:])}</blockquote>")
        elif line.startswith("- ") or line.startswith("* "):
            items = []
            while i < len(lines) and (lines[i].startswith("- ") or lines[i].startswith("* ")):
                items.append(f"<li>{_inline(lines[i][2:])}</li>")
                i += 1
            html_parts.append("<ul>" + "".join(items) + "</ul>")
            continue
        elif re.match(r"^\d+\. ", line):
            items = []
            while i < len(lines) and re.match(r"^\d+\. ", lines[i]):
                items.append(f"<li>{_inline(re.sub(r'^\d+\. ', '', lines[i]))}</li>")
                i += 1
            html_parts.append("<ol>" + "".join(items) + "</ol>")
            continue
        elif line.strip() == "":
            html_parts.append("")
        else:
            html_parts.append(f"<p>{_inline(line)}</p>")

        i += 1

    return "\n".join(html_parts)


def _inline(text: str) -> str:
    """Apply inline Markdown formatting."""
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"\*(.+?)\*",     r"<em>\1</em>", text)
    text = re.sub(r"`(.+?)`",       r"<code>\1</code>", text)
    text = re.sub(r"\[(.+?)\]\((.+?)\)", r'<a href="\2">\1</a>', text)
    return text


# ── HTML → PDF ───────────────────────────────────────────────────────────────

def _html_to_pdf(html: str) -> bytes:
    """Try WeasyPrint first, fall back to a basic ReportLab PDF."""
    try:
        from weasyprint import HTML
        return HTML(string=html).write_pdf()
    except ImportError:
        pass

    try:
        return _reportlab_fallback(html)
    except Exception as e:
        raise RuntimeError(f"PDF generation failed: {e}. Install weasyprint or reportlab.")


def _reportlab_fallback(html: str) -> bytes:
    """
    Minimal PDF using ReportLab when WeasyPrint isn't available.
    Strips HTML tags and produces a plain text PDF.
    """
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
    from reportlab.lib.units import cm
    from reportlab.lib import colors

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=2*cm, rightMargin=2*cm,
                            topMargin=2*cm, bottomMargin=2*cm)

    styles = getSampleStyleSheet()
    story = []

    # Strip HTML and render as paragraphs
    text = re.sub(r"<[^>]+>", " ", html)
    for line in text.split("\n"):
        line = line.strip()
        if line:
            story.append(Paragraph(line, styles["Normal"]))
            story.append(Spacer(1, 4))

    doc.build(story)
    return buf.getvalue()
